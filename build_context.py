#!/usr/bin/env python3
"""Turn osm-context.json (from osm_context.py) into data/sanyo-context.js for the page.

Classifies ways into layers, clips them to a corridor around the line,
simplifies them (Douglas-Peucker) and writes local-metre coordinates
(x east, z south, same origin as data/sanyo-line.js).

Layers: coast, river, motorway, trunk, jr (JR conventional lines), rail (other railways).
Usage: python3 build_context.py [osm-context.json] [data/sanyo-context.js]   (standard library only)
"""
import json, math, os, re, sys
from collections import defaultdict

LINE_JS = "data/sanyo-line.js"
# corridor half-width (m) and simplification tolerance (m) per layer
LAYERS = {"coast": (20000, 15), "river": (15000, 15), "motorway": (15000, 8),
          "trunk": (12000, 10), "jr": (15000, 6), "rail": (12000, 8)}
JR = re.compile(r"旅客鉄道|^JR|Japan Railways")


def log(msg=""):
    print(msg, file=sys.stderr, flush=True)


def layer_of(t):
    if t.get("natural") == "coastline":
        return "coast"
    if t.get("waterway") == "river":
        return "river"
    if t.get("highway") in ("motorway", "trunk"):
        return t["highway"]
    if t.get("railway") == "rail":
        if t.get("highspeed") == "yes" or "新幹線" in t.get("name", "") or t.get("service"):
            return None
        return "jr" if JR.search(t.get("operator", "")) or JR.search(t.get("name", "")) else "rail"
    return None


def dp(pts, tol):
    """Douglas-Peucker, iterative."""
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, az = pts[a]; bx, bz = pts[b]
        dx, dz = bx - ax, bz - az
        L = math.hypot(dx, dz) or 1e-9
        best, bi = -1.0, -1
        for i in range(a + 1, b):
            d = abs((pts[i][0] - ax) * dz - (pts[i][1] - az) * dx) / L
            if d > best:
                best, bi = d, i
        if best > tol:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def main(src, dst):
    txt = open(LINE_JS, encoding="utf-8").read()
    line = json.loads(txt[txt.index("=") + 1: txt.rindex(";")])
    lat0, lon0 = line["origin"]
    kx, kz = 111320 * math.cos(math.radians(lat0)), 110574
    to_xz = lambda lon, lat: ((lon - lon0) * kx, -(lat - lat0) * kz)
    cl = [(line["xz"][i], line["xz"][i + 1]) for i in range(0, len(line["xz"]), 2)][::10]  # every 500 m

    CELL = 5000.0
    grid = defaultdict(list)
    for p in cl:
        grid[(int(p[0] // CELL), int(p[1] // CELL))].append(p)

    def dist_to_line(p, limit):
        k = int(limit // CELL) + 1
        cx, cz = int(p[0] // CELL), int(p[1] // CELL)
        best = 1e18
        for dx in range(-k, k + 1):
            for dz in range(-k, k + 1):
                for q in grid.get((cx + dx, cz + dz), ()):
                    best = min(best, (q[0] - p[0]) ** 2 + (q[1] - p[1]) ** 2)
        return math.sqrt(best)

    raw = json.load(open(src, encoding="utf-8"))
    out = {k: [] for k in LAYERS}
    stats = {k: [0, 0, 0.0] for k in LAYERS}  # ways in, points out, km out
    skipped = 0
    for w in raw["ways"]:
        lay = layer_of(w["tags"])
        if not lay:
            skipped += 1
            continue
        half, tol = LAYERS[lay]
        stats[lay][0] += 1
        pts = [to_xz(*c) for c in w["coords"]]
        # split into runs that stay inside the corridor
        runs, cur = [], []
        for p in pts:
            if dist_to_line(p, half) <= half:
                cur.append(p)
            elif cur:
                runs.append(cur); cur = []
        if cur:
            runs.append(cur)
        for r in runs:
            if len(r) < 2:
                continue
            s = dp(r, tol)
            stats[lay][1] += len(s)
            stats[lay][2] += sum(math.dist(a, b) for a, b in zip(s, s[1:])) / 1000
            out[lay].append([v for p in s for v in (round(p[0]), round(p[1]))])
    for k, (n, npts, km) in stats.items():
        log(f"  {k:9s} {n:5d} ways -> {len(out[k]):5d} lines, {npts:7d} points, {km:7.0f} km")
    if skipped:
        log(f"  skipped {skipped} ways (Shinkansen, service track or unknown type)")

    os.makedirs(os.path.dirname(dst) or ".", exist_ok=True)
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by build_context.py from OpenStreetMap data (© OpenStreetMap contributors, ODbL)\n")
        f.write("window.SANYO_CONTEXT=" + json.dumps({"source": raw.get("source"), "origin": [lat0, lon0], "layers": out},
                                                    ensure_ascii=False, separators=(",", ":")) + ";\n")
    log(f"wrote {dst} ({os.path.getsize(dst) / 1024:.0f} KB)")


if __name__ == "__main__":
    a = sys.argv[1:]
    main(a[0] if a else "osm-context.json", a[1] if len(a) > 1 else "data/sanyo-context.js")
